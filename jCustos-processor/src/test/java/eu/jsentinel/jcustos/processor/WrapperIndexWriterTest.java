package eu.jsentinel.jcustos.processor;

import com.google.testing.compile.Compilation;
import com.google.testing.compile.Compiler;
import com.google.testing.compile.JavaFileObjects;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import javax.tools.JavaFileObject;
import javax.tools.StandardLocation;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Optional;

import static com.google.testing.compile.CompilationSubject.assertThat;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

@DisplayName("SecuredAnnotationProcessor — wrapper-index writer (V00.73)")
class WrapperIndexWriterTest {

  private static final String INDEX_PATH = "META-INF/jcustos/generated-wrappers.idx";
  private static final String MARKER = "# generated by jCustos-processor";

  /**
   * The {@code proxybuilder.version} property of jCustos-processor's POM, handed to the
   * tests by Surefire: the index has to name the proxybuilder release the build uses.
   */
  private static final String POM_PROXYBUILDER_VERSION =
      System.getProperty("jcustos.test.proxybuilder.version");

  /** The version field every index row carries in this build. */
  private static final String VERSION = SecuredAnnotationProcessor.proxyBuilderVersion();

  private Compilation compile(JavaFileObject... sources) {
    return Compiler.javac()
        .withProcessors(new SecuredAnnotationProcessor())
        .compile(sources);
  }

  @Test
  @DisplayName("single @Secured class emits one index row with its guarded method")
  void singleSecuredClass_emitsOneIndexEntry() throws IOException {
    JavaFileObject source = JavaFileObjects.forSourceLines(
        "demo.DocService",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;",
        "",
        "@Secured",
        "public class DocService {",
        "    @RequiresPermission(\"doc:delete\")",
        "    public void delete(final String id) {}",
        "}");

    Compilation result = compile(source);
    assertThat(result).succeeded();

    String content = readIndex(result);
    assertNotNull(content, "index file expected");
    assertTrue(content.startsWith(MARKER + "\n"), "marker comment expected at top");

    List<String> rows = dataRows(content);
    assertEquals(1, rows.size(), "exactly one data row expected");
    assertEquals("demo.DocService:demo.DocServiceSecured:proxybuilder:" + VERSION
            + ":delete:secured",
        rows.get(0));
  }

  @Test
  @DisplayName("the index names the proxybuilder release of the build, not a literal that goes stale")
  void indexNamesTheProxyBuilderVersionOfTheBuild() {
    assertNotNull(POM_PROXYBUILDER_VERSION,
        "run through Maven: Surefire passes the POM property jcustos.test.proxybuilder.version");
    assertEquals(POM_PROXYBUILDER_VERSION, VERSION,
        "the index must carry the proxybuilder version jCustos-processor is built with");
    assertFalse(SecuredAnnotationProcessor.UNKNOWN_PROXYBUILDER_VERSION.equals(VERSION));
  }

  @Test
  @DisplayName("two @Secured classes emit two rows sorted by sourceFqn")
  void twoSecuredClasses_emitSortedRows() throws IOException {
    JavaFileObject a = JavaFileObjects.forSourceLines(
        "demo.Zebra",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;",
        "@Secured public class Zebra {",
        "  @RequiresPermission(\"z:read\") public void z() {}",
        "}");
    JavaFileObject b = JavaFileObjects.forSourceLines(
        "demo.Alpha",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;",
        "@Secured public class Alpha {",
        "  @RequiresPermission(\"a:read\") public void a() {}",
        "}");

    Compilation result = compile(a, b);
    assertThat(result).succeeded();

    List<String> rows = dataRows(readIndex(result));
    assertEquals(2, rows.size());
    assertTrue(rows.get(0).startsWith("demo.Alpha:"),
        "Alpha must sort before Zebra; got: " + rows);
    assertTrue(rows.get(1).startsWith("demo.Zebra:"));
  }

  @Test
  @DisplayName("compiling the same source twice produces byte-identical index files")
  void incrementalRebuild_isIdempotent() throws IOException {
    JavaFileObject source = JavaFileObjects.forSourceLines(
        "demo.Foo",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;",
        "@Secured public class Foo {",
        "  @RequiresPermission(\"f:do\") public void doIt() {}",
        "}");

    String first = readIndex(compile(source));
    String second = readIndex(compile(source));
    assertEquals(first, second, "two independent compilations must produce identical index bytes");
  }

  @Test
  @DisplayName("marker comment is always present")
  void markerCommentIsPresent() throws IOException {
    JavaFileObject source = JavaFileObjects.forSourceLines(
        "demo.Bar",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;",
        "@Secured public class Bar {",
        "  @RequiresPermission(\"b:do\") public void doIt() {}",
        "}");
    String content = readIndex(compile(source));
    assertTrue(content.split("\n")[0].equals(MARKER));
  }

  @Test
  @DisplayName("a compilation with no @Secured classes does not produce an index file")
  void noSecuredClasses_emitsNoIndexFile() {
    JavaFileObject source = JavaFileObjects.forSourceLines(
        "demo.Plain",
        "package demo;",
        "public class Plain { public void open() {} }");

    Compilation result = compile(source);
    assertThat(result).succeeded();
    Optional<JavaFileObject> index = result.generatedFile(
        StandardLocation.CLASS_OUTPUT, INDEX_PATH);
    assertFalse(index.isPresent(),
        "no @Secured input → no index file expected");
  }

  @Test
  @DisplayName("methods without a security annotation are omitted from the index row")
  void onlyGuardedMethodsAreIndexed() throws IOException {
    JavaFileObject source = JavaFileObjects.forSourceLines(
        "demo.Mixed",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;",
        "@Secured public class Mixed {",
        "  @RequiresPermission(\"m:do\") public void guarded() {}",
        "  public void open() {}",
        "}");

    Compilation result = compile(source);
    assertThat(result).succeeded();
    List<String> rows = dataRows(readIndex(result));
    assertEquals(1, rows.size());
    // method list is in position 5; guarded only
    // V00.74: the sixth :kind suffix is now present; split with limit 6.
    String[] parts = rows.get(0).split(":", 6);
    assertEquals("guarded", parts[4]);
    assertEquals("secured", parts[5]);
  }

  @Test
  @DisplayName("JS-SEC-156: a method guarded through the generic call is indexed; one that only gets the deny-by-default call is not")
  void genericallyGuardedMethodsAreIndexed() throws IOException {
    JavaFileObject evaluator = JavaFileObjects.forSourceLines(
        "demo.OwnerOnly",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.ProtectedBy;",
        "import eu.jsentinel.jcustos.authorization.api.AuthorizationDecision;",
        "import eu.jsentinel.jcustos.authorization.api.AuthorizationEvaluator;",
        "import eu.jsentinel.jcustos.authorization.navigation.AccessContext;",
        "public final class OwnerOnly implements AuthorizationEvaluator<ProtectedBy> {",
        "  @Override",
        "  public AuthorizationDecision evaluate(AccessContext context, ProtectedBy annotation) {",
        "    return AuthorizationDecision.forbidden(\"always denied\");",
        "  }",
        "}");
    JavaFileObject base = JavaFileObjects.forSourceLines(
        "demo.OwnedBase",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.ProtectedBy;",
        "@ProtectedBy(OwnerOnly.class) public class OwnedBase {",
        "  public void inherited() {}",
        "}");
    JavaFileObject owned = JavaFileObjects.forSourceLines(
        "demo.Owned",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "@Secured public class Owned extends OwnedBase {",
        "  public void own() {}",
        "}");
    JavaFileObject mixed = JavaFileObjects.forSourceLines(
        "demo.Mixed",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.ProtectedBy;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "@Secured public class Mixed {",
        "  @ProtectedBy(OwnerOnly.class) public void guarded() {}",
        "  public void open() {}",
        "}");

    Compilation result = compile(evaluator, base, owned, mixed);
    assertThat(result).succeeded();
    List<String> rows = dataRows(readIndex(result));
    assertEquals(List.of(
            "demo.Mixed:demo.MixedSecured:proxybuilder:" + VERSION + ":guarded:secured",
            "demo.Owned:demo.OwnedSecured:proxybuilder:" + VERSION + ":own,inherited:secured"),
        rows);
  }

  @Test
  @DisplayName("JS-SEC-159: an override that carries no annotation but overrides a restricted declaration is indexed")
  void overrideOfRestrictedDeclarationIsIndexed() throws IOException {
    JavaFileObject contract = JavaFileObjects.forSourceLines(
        "demo.Contract",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresRole;",
        "public interface Contract {",
        "  @RequiresRole(\"ADMIN\") void purge();",
        "  void list();",
        "}");
    JavaFileObject base = JavaFileObjects.forSourceLines(
        "demo.Base",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;",
        "public class Base {",
        "  @RequiresPermission(\"doc:archive\") public void archive() {}",
        "}");
    JavaFileObject service = JavaFileObjects.forSourceLines(
        "demo.Overriding",
        "package demo;",
        "import eu.jsentinel.jcustos.authorization.annotations.PublicRoute;",
        "import eu.jsentinel.jcustos.authorization.annotations.Secured;",
        "@Secured public class Overriding extends Base implements Contract {",
        "  @Override public void purge() {}",
        "  @Override public void list() {}",
        "  @PublicRoute @Override public void archive() {}",
        "}");

    Compilation result = compile(contract, base, service);
    assertThat(result).succeeded();
    // list() overrides an unrestricted declaration, archive() opts out with @PublicRoute.
    assertEquals(List.of("demo.Overriding:demo.OverridingSecured:proxybuilder:" + VERSION
            + ":purge:secured"),
        dataRows(readIndex(result)));
  }

  // ── helpers ──────────────────────────────────────────────────────

  private static String readIndex(Compilation compilation) throws IOException {
    Optional<JavaFileObject> opt = compilation.generatedFile(
        StandardLocation.CLASS_OUTPUT, INDEX_PATH);
    assertTrue(opt.isPresent(), "expected " + INDEX_PATH + " in compilation output");
    return readContent(opt.get());
  }

  private static String readContent(JavaFileObject file) throws IOException {
    try (InputStream in = file.openInputStream()) {
      return new String(in.readAllBytes(), StandardCharsets.UTF_8);
    }
  }

  private static List<String> dataRows(String content) {
    return content.lines()
        .filter(l -> !l.isBlank())
        .filter(l -> !l.startsWith("#"))
        .toList();
  }
}
