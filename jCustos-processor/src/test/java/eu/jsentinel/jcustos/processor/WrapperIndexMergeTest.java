package eu.jsentinel.jcustos.processor;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Processor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.StandardJavaFileManager;
import javax.tools.StandardLocation;
import javax.tools.ToolProvider;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The wrapper-index writer against a real class-output directory: an incremental
 * compilation finds the index of an earlier one and has to merge it, and a class-output
 * directory where the index cannot be written must not fail the build. The compiler is the
 * JDK's own, the directories are real; {@code WrapperIndexWriterTest} covers the fresh
 * compilation in memory, where no earlier index can exist.
 */
@DisplayName("SecuredAnnotationProcessor - wrapper-index merge and write failure on a real class-output directory")
class WrapperIndexMergeTest {

  private static final String INDEX_PATH = "META-INF/jcustos/generated-wrappers.idx";
  private static final String MARKER = "# generated by jCustos-processor";
  private static final String VERSION = SecuredAnnotationProcessor.proxyBuilderVersion();
  private static final String ANY_VERSION = "<version>";

  private static final String FOO = """
      package demo;
      import eu.jsentinel.jcustos.authorization.annotations.RequiresPermission;
      import eu.jsentinel.jcustos.authorization.annotations.Secured;
      @Secured public class Foo {
        @RequiresPermission("f:do") public void doIt() {}
      }
      """;

  @TempDir
  Path work;

  @Test
  @DisplayName("an earlier index is merged: other sources' rows stay (trimmed, de-duplicated), the recompiled source's row is replaced, malformed rows are dropped")
  void earlierIndex_isMergedNotOverwritten() throws IOException {
    Path classes = work.resolve("classes");
    seedIndex(classes,
        MARKER,
        "",
        "# note:with:enough:colons:to:look:like:a:row",
        " demo.Old : demo.OldSecured:proxybuilder:0.0.1: archive , purge ,archive:secured",
        "demo.Foo:demo.FooSecured:proxybuilder:0.0.1:stale:secured",
        "demo.Five:demo.FiveSecured:proxybuilder:0.0.1:run",
        "demo.Four:demo.FourSecured:proxybuilder:0.0.1",
        "demo.Empty:demo.EmptySecured:proxybuilder:0.0.1::secured");

    Outcome outcome = compile(classes, FOO);

    assertTrue(outcome.success(), outcome.toString());
    List<String> rows = dataRows(readIndex(classes));
    // The version field of a carried-over row is left out of the comparison: the writer
    // keeps only the method list of an earlier row and stamps the current version on it.
    assertEquals(Stream.of(
                row("demo.Empty", ""),
                row("demo.Five", "run"),
                row("demo.Foo", "doIt"),
                row("demo.Old", "archive,purge"))
            .map(WrapperIndexMergeTest::withoutVersion).toList(),
        rows.stream().map(WrapperIndexMergeTest::withoutVersion).toList(),
        "merged index expected; a row with fewer than five fields and the comment are not rows");
    // The recompiled source's row is the one this compilation wrote, version included.
    assertEquals(row("demo.Foo", "doIt"), rows.get(2));
  }

  @Test
  @DisplayName("an index that cannot be written is a WARNING; the wrapper is generated and the build succeeds")
  void unwritableIndex_warnsAndKeepsTheBuildGreen() throws IOException {
    Path classes = work.resolve("classes");
    // META-INF/jcustos exists as a plain file, so the index's directory cannot be created.
    Files.createDirectories(classes.resolve("META-INF"));
    Files.writeString(classes.resolve("META-INF/jcustos"), "not a directory");

    Outcome outcome = compile(classes, FOO);

    assertTrue(outcome.success(), "an index problem must not fail the compilation: " + outcome);
    assertTrue(outcome.diagnostics().stream()
            .anyMatch(d -> d.getKind() == Diagnostic.Kind.WARNING
                && d.getMessage(Locale.ROOT).contains("processor/index-write-failed")),
        "expected the processor/index-write-failed WARNING: " + outcome);
    assertTrue(Files.isRegularFile(classes.resolve("demo/FooSecured.class")),
        "the wrapper must still be generated");
  }

  @Test
  @DisplayName("an index another processor has already written is a WARNING, not a failed build")
  void indexTakenByAnotherProcessor_warnsAndKeepsTheBuildGreen() throws IOException {
    Path classes = work.resolve("classes");

    Outcome outcome = compile(classes, FOO, new CompetingWriter(INDEX_PATH));

    assertTrue(outcome.success(), "an index problem must not fail the compilation: " + outcome);
    assertTrue(outcome.diagnostics().stream()
            .anyMatch(d -> d.getKind() == Diagnostic.Kind.WARNING
                && d.getMessage(Locale.ROOT).contains("processor/index-write-failed")),
        "expected the processor/index-write-failed WARNING: " + outcome);
    assertEquals(CompetingWriter.CONTENT, Files.readString(classes.resolve(INDEX_PATH)),
        "the other processor's file is left as it is");
    assertTrue(Files.isRegularFile(classes.resolve("demo/FooSecured.class")),
        "the wrapper must still be generated");
  }

  // ── helpers ──────────────────────────────────────────────────────

  /** Creates {@code path} in the first round, before the processor under test writes it. */
  @SupportedAnnotationTypes("*")
  private static final class CompetingWriter extends AbstractProcessor {
    private static final String CONTENT = "# written by another processor\n";
    private final String path;
    private boolean written;

    private CompetingWriter(String path) {
      this.path = path;
    }

    @Override
    public SourceVersion getSupportedSourceVersion() {
      return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
      if (!written) {
        written = true;
        try (Writer w = processingEnv.getFiler()
            .createResource(StandardLocation.CLASS_OUTPUT, "", path).openWriter()) {
          w.write(CONTENT);
        } catch (IOException io) {
          throw new UncheckedIOException(io);
        }
      }
      return false;
    }
  }

  private record Outcome(boolean success, List<Diagnostic<? extends JavaFileObject>> diagnostics) {
    @Override
    public String toString() {
      StringBuilder text = new StringBuilder("success=").append(success);
      diagnostics.forEach(d -> text.append("\n  ").append(d.getKind()).append(' ')
          .append(d.getMessage(Locale.ROOT)));
      return text.toString();
    }
  }

  /**
   * Compiles {@code demo.Foo} into {@code classes}, a real directory, with
   * {@code firstProcessors} ahead of the processor under test.
   */
  private Outcome compile(Path classes, String fooSource, Processor... firstProcessors)
      throws IOException {
    Path sources = work.resolve("src/demo");
    Files.createDirectories(sources);
    Path foo = Files.writeString(sources.resolve("Foo.java"), fooSource);
    Path generated = Files.createDirectories(work.resolve("generated"));
    Files.createDirectories(classes);

    JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
    DiagnosticCollector<JavaFileObject> collector = new DiagnosticCollector<>();
    try (StandardJavaFileManager files =
             javac.getStandardFileManager(collector, Locale.ROOT, StandardCharsets.UTF_8)) {
      files.setLocationFromPaths(StandardLocation.CLASS_OUTPUT, List.of(classes));
      files.setLocationFromPaths(StandardLocation.SOURCE_OUTPUT, List.of(generated));
      JavaCompiler.CompilationTask task = javac.getTask(null, files, collector,
          List.of("-proc:full"), null, files.getJavaFileObjectsFromPaths(List.of(foo)));
      List<Processor> processors = new ArrayList<>(List.of(firstProcessors));
      processors.add(new SecuredAnnotationProcessor());
      task.setProcessors(processors);
      boolean success = task.call();
      return new Outcome(success, List.copyOf(collector.getDiagnostics()));
    }
  }

  private static void seedIndex(Path classes, String... lines) throws IOException {
    Path index = classes.resolve(INDEX_PATH);
    Files.createDirectories(index.getParent());
    Files.writeString(index, String.join("\n", lines) + "\n");
  }

  private static String readIndex(Path classes) throws IOException {
    String content = Files.readString(classes.resolve(INDEX_PATH));
    assertTrue(content.startsWith(MARKER + "\n"), "marker comment expected at top: " + content);
    return content;
  }

  private static List<String> dataRows(String content) {
    return content.lines()
        .filter(l -> !l.isBlank())
        .filter(l -> !l.startsWith("#"))
        .toList();
  }

  /** Replaces the version field (the fourth) of an index row with {@link #ANY_VERSION}. */
  private static String withoutVersion(String row) {
    String[] fields = row.split(":", 6);
    fields[3] = ANY_VERSION;
    return String.join(":", fields);
  }

  private static String row(String sourceFqn, String methods) {
    return sourceFqn + ":" + sourceFqn + "Secured:proxybuilder:" + VERSION + ":" + methods + ":secured";
  }
}
